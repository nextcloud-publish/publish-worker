<?php

declare(strict_types=1);

namespace App\Message;

/**
 * Encodes and decodes the messages send via symfony messenger, which the publish API enqueues.
 * It declares the same namespace, class name and property names:
 * Messenger picks the target class from the message's `type` header
 * ("App\Message\BuildJob"), then the serializer maps JSON keys onto constructor parameter names,
 * so a mismatch on either breaks decoding.
 * publish validates every field before enqueueing, so the worker uses them unchecked; ssg-library checks render_options.
 *
 * @param ?string $build_id Per-build UUID v7 generated by publish's client, names the job's folder under BUILDS_DIR.
 *                         null for a delete, which builds nothing.
 * @param string $static_site_id Identifies the site in publish's static_site table.
 * @param BuildOperation $operation What to do with the site.
 * @param string $slug Unique across sites; names the site's directory under PAGES_DIR and its URL path.
 * @param string $callback_status_url Callback url to update the build status
 * @param string $created_at Timestamp when the job was created by the publish API.
 * @param ?string $content_download_url Download url for the build assets; set for create and update.
 * @param ?string $title Site title, shown in the page header; set for create and update.
 * @param mixed $render_options Any JSON value from the build request, passed to ssg-library, which validates it.
 *                              null when absent.
 */
final class BuildJob
{
    public function __construct(
        public readonly ?string $build_id,
        public readonly string $static_site_id,
        public readonly BuildOperation $operation,
        public readonly string $slug,
        public readonly string $callback_status_url,
        public readonly string $created_at,
        public readonly ?string $content_download_url = null,
        public readonly ?string $title = null,
        public readonly mixed $render_options = null,
    ) {
    }
}
